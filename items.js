// "רשימה חכמה" לנושא שלא נמצא במאגר: מחפשים מילות מפתח, ואם אין התאמה בונים רשימה כללית.
window.smartItemsFor = function (topic) {
  const t = (topic || "").trim();
  if (!t) return null;
  const norm = t.replace(/["'׳״]/g, "");
  for (const p of window.PRODUCTS) {
    if (p.name === t) return { product: p, matched: true };
  }
  for (const p of window.PRODUCTS) {
    if (p.aliases.some(a => norm.includes(a.replace(/["'׳״]/g, "")))) {
      return { product: { ...p, name: t }, matched: true };
    }
  }
  // אין התאמה: שלד כללי שאפשר לערוך
  const generic = [
    ["🧱", `הבסיס של ה${t}`], ["⭐", `הדבר הכי חשוב ב${t}`], ["➕", "תוספת ראשונה"], ["➕", "תוספת שנייה"],
    ["✨", "שדרוג פרימיום"], ["🎨", "עיצוב וסטייל"], ["🧰", "אביזר נלווה"], ["🎁", "בונוס הפתעה"]
  ];
  return { product: { id: "custom", name: t, emoji: "🛒", items: generic }, matched: false };
};
